import { describe, expect, it } from 'vitest';
import { isPublicAddress } from '../../src/server/adapters/web/public-address.js';

describe('public address policy snapshot', () => {
  it('checks every IPv4 /8 allocation using addresses outside special subranges', () => {
    for (let octet = 0; octet <= 255; octet++) {
      const expected = octet >= 1 && octet <= 223 && octet !== 10 && octet !== 127;
      expect(isPublicAddress(`${octet}.1.1.1`), `octet ${octet}`).toBe(expected);
    }
  });

  it.each([
    '0.0.0.0', '0.255.255.255', '10.0.0.0', '10.255.255.255',
    '100.64.0.0', '100.127.255.255', '127.0.0.0', '127.255.255.255',
    '169.254.0.0', '169.254.255.255', '172.16.0.0', '172.31.255.255',
    '192.0.0.0', '192.0.0.8', '192.0.0.9', '192.0.0.170', '192.0.0.171', '192.0.0.255',
    '192.0.2.0', '192.0.2.255', '192.88.99.0', '192.88.99.2', '192.88.99.255',
    '192.168.0.0', '192.168.255.255', '198.18.0.0', '198.19.255.255',
    '198.51.100.0', '198.51.100.255', '203.0.113.0', '203.0.113.255',
    '192.175.48.0', '192.31.196.255', '192.52.193.1', '224.0.0.0',
    '239.255.255.255', '240.0.0.0', '255.255.255.255',
    '::', '::1', '::ffff:8.8.8.8', '::ffff:127.0.0.1', '64:ff9b::808:808',
    '2001::1', '2001:1::1', '2001:1::2', '2001:1::3', '2001:2::1',
    '2001:3::1', '2001:4:112::1', '2001:10::1', '2001:20::1', '2001:30::1',
    '2001:db8::1', '2002:808:808::1', '2620:4f:8000::1', '3fff::1',
    '4000::1', '5f00::1', 'fc00::1', 'fe80::1', 'ff02::1',
    '', 'bad', '8.8.8.999', '1.2.3', '01.2.3.4', 'fe80::1%eth0', '2606::1%eth0',
  ])('rejects %s', address => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each([
    '1.0.0.1', '8.8.8.8', '100.63.255.255', '100.128.0.0',
    '169.253.255.255', '169.255.0.0', '172.15.255.255', '172.32.0.0',
    '192.0.1.255', '192.0.3.0', '192.88.98.255', '192.88.100.0',
    '192.167.255.255', '192.169.0.0', '198.17.255.255', '198.20.0.0',
    '198.51.99.255', '198.51.101.0', '203.0.112.255', '203.0.114.0',
    '2001:200::1', '2001:400::1', '2001:800::1', '2001:1200::1',
    '2001:2000::1', '2001:4000::1', '2001:5000::1', '2001:8000::1',
    '2003::1', '2400::1', '2410::1', '2606:4700:4700::1111',
    '2610::1', '2620::1', '2630::1', '2800::1', '2a00::1', '2a10::1', '2c00::1',
  ])('accepts %s', address => {
    expect(isPublicAddress(address)).toBe(true);
  });

  it.each(['2001:1000::1', '2001:4e00::1', '2001:6000::1', '2003:4000::1',
    '2420::1', '2612::1', '2622::1', '2640::1', '2900::1', '2a20::1', '2d00::1'])(
    'rejects unallocated IPv6 gap %s', address => {
    expect(isPublicAddress(address)).toBe(false);
  });
});
