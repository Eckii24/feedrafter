import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { createServer } from 'node:net';
import { setTimeout as delay } from 'node:timers/promises';
import { test, expect } from '@playwright/test';
import { createDatabase } from '../../src/server/adapters/postgres/client.js';
import { migrateDatabase } from '../../src/server/adapters/postgres/migrate.js';
import { ImportStore } from '../../src/server/adapters/postgres/import-store.js';
import { buildHttpApp } from '../../src/server/http/app.js';

const docker = (...args: string[]) => execFileSync('docker', ['--host', 'unix:///var/run/docker.sock', ...args], { encoding: 'utf8' }).trim();

test('built reader uses the same-origin Fastify and PostgreSQL API', async ({ page }) => {
  test.setTimeout(60000);
  let container = '';
  let database: ReturnType<typeof createDatabase> | undefined;
  let app: Awaited<ReturnType<typeof buildHttpApp>> | undefined;
  try {
    container = docker('run', '--detach', '--rm', '--pull=never', '--name', `feedrafter-ui-${randomUUID()}`, '-e', 'POSTGRES_PASSWORD=disposable-test-only', '-e', 'POSTGRES_DB=feedrafter_test', '-p', '127.0.0.1::5432', 'postgres:18');
    const match = /^127\.0\.0\.1:(\d+)$/.exec(docker('port', container, '5432/tcp'));
    if (!match) throw new Error('Unexpected PostgreSQL port');
    database = createDatabase(`postgresql://postgres:disposable-test-only@127.0.0.1:${match[1]}/feedrafter_test`);
    let ready = false;
    for (let i = 0; i < 100; i++) { try { await database.pool.query('select 1'); ready = true; break; } catch { await delay(200); } }
    if (!ready) throw new Error('Disposable PostgreSQL did not become ready');
    await migrateDatabase(database.pool);
    const store = new ImportStore(database.db);
    const context = await store.ensureContext('ui-test', 'account');
    const [articleId, otherId] = await store.importPage(context.id, [
      { id: 'ui-real-article', title: 'Real server article', url: 'https://example.org/article', author: 'Writer', publishedAt: null, feedId: 'feed/real', feedTitle: 'Real feed' },
      { id: 'ui-second-article', title: 'Second server article', url: null, author: null, publishedAt: null, feedId: 'feed/real', feedTitle: 'Real feed' },
      { id: 'ui-unscored-article', title: 'Unscored server article', url: null, author: null, publishedAt: null, feedId: 'feed/real', feedTitle: 'Real feed' },
    ], new Date());
    const scoreId = (await database.pool.query("insert into score_definitions(name, description, prompt) values ('Browser rank', 'test', 'test') returning id")).rows[0].id as string;
    await database.pool.query('insert into article_scores(article_id, score_id, value, calculated_at, content_revision, assignment_revision) values ($1, $2, 0, now(), 0, 0), ($3, $2, 75.5, now(), 0, 0)', [articleId, scoreId, otherId]);
    await database.pool.query("insert into score_definitions(name, description, prompt, active) values ('Hidden rank', 'test', 'test', false)");
    const tag = (await database.pool.query("insert into tags(label, key) values ('Local topic', '') returning id")).rows[0].id as string;
    await database.pool.query('insert into article_tags(article_id, tag_id) values ($1, $2)', [articleId, tag]);
    const oldTag = (await database.pool.query("insert into tags(label, key, archived_at) values ('Historical topic', '', now()) returning id")).rows[0].id as string;
    await database.pool.query('insert into article_tags(article_id, tag_id) values ($1, $2)', [articleId, oldTag]);
    await database.pool.query("insert into tags(label, key) values ('New topic', '')");
    const socket = createServer();
    await new Promise<void>(resolve => socket.listen(0, '127.0.0.1', resolve));
    const address = socket.address();
    if (!address || typeof address === 'string') throw new Error('No port');
    const port = address.port;
    await new Promise<void>((resolve, reject) => socket.close(error => error ? reject(error) : resolve()));
    app = await buildHttpApp({ db: database.db, pool: database.pool, origin: `http://127.0.0.1:${port}`, trustedProxies: [] });
    await app.listen({ host: '127.0.0.1', port });
    await page.goto(`http://127.0.0.1:${port}/`);
    await expect(page.getByLabel('Sort by')).toHaveValue('date');
    await page.getByLabel('Sort by').selectOption('score');
    await expect(page.getByLabel(/^Score/).getByRole('option', { name: 'Browser rank' })).toHaveCount(1);
    await expect(page.getByLabel(/^Score/).getByRole('option', { name: 'Hidden rank' })).toHaveCount(0);
    await page.getByLabel(/^Score/).selectOption(scoreId);
    await page.getByRole('button', { name: 'Apply filters' }).click();
    const list = page.getByRole('region', { name: 'Articles' }).locator('ul.articles');
    await expect(list.locator('li').first()).toContainText('Second server article');
    await expect(list.locator('li').first()).toContainText('Score: 75.5');
    await expect(list.locator('li').nth(1)).toContainText('Score: 0');
    await expect(list.locator('li').last()).toContainText('Unscored server article');
    await expect(list.locator('li').last()).toContainText('Score: Not scored');
    await page.getByLabel('Order').selectOption('asc');
    await page.getByRole('button', { name: 'Apply filters' }).click();
    await expect(list.locator('li').first()).toContainText('Real server article');
    await page.getByLabel('Sort by').selectOption('date');
    await page.getByRole('button', { name: 'Apply filters' }).click();
    await page.getByRole('button', { name: 'Catalog settings' }).click();
    await expect(page.getByRole('heading', { name: 'Catalog settings' })).toBeFocused();
    await expect(page.getByText('Fallback category (protected)')).toBeVisible();
    await expect(page.getByRole('button', { name: 'Archive Nicht zugeordnet' })).toHaveCount(0);
    for (const kind of ['category', 'tag'] as const) {
      const table = kind === 'category' ? 'categories' : 'tags';
      const input = page.getByLabel(`New ${kind}`);
      const create = page.getByRole('button', { name: `Create ${kind}` });
      for (const expectedStatus of [201, 409]) {
        const before = (await database.pool.query(`select * from ${table} order by id`)).rows;
        await input.fill(`Browser ${kind}`);
        await input.focus();
        await page.keyboard.press('Tab');
        await expect(create).toBeFocused();
        let release!: () => void;
        const gate = new Promise<void>(resolve => { release = resolve; });
        await page.route(`**/api/v1/${table}`, async route => {
          if (route.request().method() !== 'POST') return route.continue();
          const response = await route.fetch();
          await gate;
          await route.fulfill({ response });
        });
        const response = page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1/${table}` && response.request().method() === 'POST');
        await page.keyboard.press('Enter');
        try { await expect(create).toBeDisabled(); } finally { release(); }
        expect((await response).status()).toBe(expectedStatus);
        if (expectedStatus === 201) {
          await expect(page.getByRole('status')).toHaveText('Catalog saved.');
          await expect(input).toHaveValue('');
          await expect(page.getByLabel(`Rename Browser ${kind}`)).toBeVisible();
        } else {
          await expect(page.getByRole('alert')).toHaveText('Label already exists');
          await expect(page.getByText('Catalog saved.')).toHaveCount(0);
          await expect(input).toHaveValue(`Browser ${kind}`);
          expect((await database.pool.query(`select * from ${table} order by id`)).rows).toEqual(before);
        }
        await expect(input).toBeFocused();
        await page.unroute(`**/api/v1/${table}`);
      }
      await page.getByLabel(`Rename Browser ${kind}`).fill(`Renamed ${kind}`);
      await page.getByLabel(`Rename Browser ${kind}`).focus();
      await page.keyboard.press('Tab');
      await expect(page.getByRole('button', { name: `Save Browser ${kind}` })).toBeFocused();
      await page.keyboard.press('Enter');
      await expect(page.getByLabel(`Rename Renamed ${kind}`)).toBeFocused();
      await page.keyboard.press('Tab');
      await expect(page.getByRole('button', { name: `Archive Renamed ${kind}` })).toBeFocused();
      await page.keyboard.press('Enter');
      await expect(page.getByRole('button', { name: `Archive Renamed ${kind}` })).toHaveCount(0);
      await expect(page.getByLabel(`Rename Renamed ${kind}`)).toBeFocused();
    }
    for (const label of ['Collision first', 'Collision second']) {
      await page.getByLabel('New category').fill(label);
      await page.getByRole('button', { name: 'Create category' }).click();
      await expect(page.getByLabel(`Rename ${label}`)).toBeVisible();
    }
    const categoriesBefore = (await database.pool.query("select id, label, archived_at from categories where label like 'Collision %' order by label")).rows;
    expect(categoriesBefore).toHaveLength(2);
    let catalogReloads = 0;
    page.on('request', request => {
      if (request.method() === 'GET' && /\/api\/v1\/(categories|tags)$/.test(new URL(request.url()).pathname)) catalogReloads++;
    });
    const firstRename = page.getByLabel('Rename Collision first');
    await firstRename.fill('Collision second');
    await firstRename.focus();
    await page.keyboard.press('Tab');
    const saveFirst = page.getByRole('button', { name: 'Save Collision first' });
    await expect(saveFirst).toBeFocused();
    let releaseConflict!: () => void;
    const conflictGate = new Promise<void>(resolve => { releaseConflict = resolve; });
    await page.route('**/api/v1/categories/*', async route => {
      const response = await route.fetch();
      await conflictGate;
      await route.fulfill({ response });
    });
    const conflictResponse = page.waitForResponse(response => response.url().includes('/api/v1/categories/') && response.request().method() === 'PATCH');
    await page.keyboard.press('Enter');
    try { await expect(saveFirst).toBeDisabled(); } finally { releaseConflict(); }
    expect((await conflictResponse).status()).toBe(409);
    await expect(page.getByRole('alert')).toHaveText('Label already exists');
    await expect(page.getByText('Catalog saved.')).toHaveCount(0);
    await expect(firstRename).toBeFocused();
    await expect(firstRename).toHaveValue('Collision second');
    await expect(page.getByLabel('Rename Collision second')).toHaveValue('Collision second');
    expect((await database.pool.query("select id, label, archived_at from categories where label like 'Collision %' order by label")).rows).toEqual(categoriesBefore);
    expect(catalogReloads).toBe(0);
    await page.unroute('**/api/v1/categories/*');
    await page.setViewportSize({ width: 375, height: 844 });
    const longLabel = 'x'.repeat(200);
    await page.getByLabel('New tag').fill(longLabel);
    await page.getByRole('button', { name: 'Create tag' }).click();
    await expect(page.getByLabel(`Rename ${longLabel}`)).toBeVisible();
    expect(await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))).toEqual({ width: 375, scroll: 375 });
    await page.setViewportSize({ width: 1280, height: 720 });
    await page.getByLabel('New tag').fill('LOCAL TOPIC');
    await page.getByRole('button', { name: 'Create tag' }).click();
    await expect(page.getByRole('alert')).toHaveText('Label already exists');
    await page.getByLabel('New tag').fill('  ');
    await page.getByRole('button', { name: 'Create tag' }).click();
    await expect(page.getByRole('alert')).toHaveText('Label is required');
    await page.getByRole('button', { name: 'Back to reader' }).click();
    await expect(page.getByRole('button', { name: 'Catalog settings' })).toBeFocused();
    await page.getByRole('button', { name: /Real server article/ }).click();
    await expect(page.getByRole('heading', { name: 'Real server article' })).toBeVisible();
    await expect(page.getByRole('link', { name: /Open original/ })).toHaveAttribute('href', 'https://example.org/article');
    const editor = page.getByRole('region', { name: 'Article catalog' });
    await expect(editor).toContainText('Historical topic (archived)');
    await expect(editor.getByLabel('Add tag').getByRole('option', { name: /Historical topic/ })).toHaveCount(0);
    await editor.getByLabel('Category').selectOption({ label: 'Collision first' });
    await editor.getByLabel('Category').focus();
    await page.keyboard.press('Tab');
    await expect(editor.getByRole('button', { name: 'Save category' })).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(editor.getByRole('status')).toHaveText('Article catalog saved.');
    await expect(editor.getByLabel('Category')).toBeFocused();
    await editor.getByLabel('Add tag').selectOption({ label: 'New topic' });
    await editor.getByRole('button', { name: 'Add tag', exact: true }).click();
    await expect(editor.getByRole('button', { name: 'Remove New topic' })).toBeVisible();
    await editor.getByRole('button', { name: 'Remove Historical topic' }).focus();
    await page.keyboard.press('Enter');
    await expect(editor.getByRole('button', { name: 'Remove Historical topic' })).toHaveCount(0);
    await expect(editor.getByLabel('Add tag')).toBeFocused();
    expect((await database.pool.query('select assignment_revision from articles where id = $1', [articleId])).rows[0].assignment_revision).toBe(3);
    await editor.getByRole('button', { name: 'Remove New topic' }).click();
    await expect(editor.getByRole('button', { name: 'Remove New topic' })).toHaveCount(0);
    const positive = page.getByRole('button', { name: 'Positive feedback' });
    const negative = page.getByRole('button', { name: 'Negative feedback' });
    const neutral = page.getByRole('button', { name: 'Neutral feedback' });
    const tagCheckbox = page.getByRole('checkbox', { name: 'tag: Local topic', exact: true });
    const sourceCheckbox = page.getByRole('checkbox', { name: 'source: Real feed', exact: true });
    const submit = page.getByRole('button', { name: 'Submit feedback' });
    const feedback = page.getByRole('region', { name: 'Targeted feedback' });
    await expect(tagCheckbox).toHaveCount(0);
    await positive.focus();
    await page.keyboard.press('Enter');
    await expect(positive).toHaveAttribute('aria-expanded', 'true');
    await expect(submit).toBeDisabled();
    await page.keyboard.press('Tab');
    await expect(negative).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(neutral).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(sourceCheckbox).toBeFocused();
    await page.keyboard.press('Space');
    await page.keyboard.press('Tab');
    await expect(tagCheckbox).toBeFocused();
    await page.keyboard.press('Space');
    expect(Number((await database.pool.query('select count(*) from source_votes')).rows[0].count)).toBe(0);
    await page.keyboard.press('Tab');
    await expect(submit).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(feedback.getByRole('status')).toHaveText('Feedback saved.');
    await expect(positive).toBeFocused();
    await expect(tagCheckbox).not.toBeChecked();
    await expect(sourceCheckbox).not.toBeChecked();
    expect((await database.pool.query('select value from tag_votes where article_id = $1', [articleId])).rows).toEqual([{ value: 1 }]);
    expect((await database.pool.query('select value from source_votes where article_id = $1', [articleId])).rows).toEqual([{ value: 1 }]);
    await sourceCheckbox.check();
    await negative.click();
    await expect(negative).toHaveAttribute('aria-expanded', 'true');
    await expect(positive).toHaveAttribute('aria-expanded', 'false');
    await expect(sourceCheckbox).not.toBeChecked();
    await expect(submit).toBeDisabled();
    await tagCheckbox.check();
    await submit.click();
    await expect(feedback.getByRole('status')).toHaveText('Feedback saved.');
    expect((await database.pool.query('select value from tag_votes where article_id = $1', [articleId])).rows).toEqual([{ value: -1 }]);
    expect((await database.pool.query('select value from source_votes where article_id = $1', [articleId])).rows).toEqual([{ value: 1 }]);
    await editor.getByRole('button', { name: 'Remove Local topic' }).click();
    await expect(editor.getByRole('button', { name: 'Remove Local topic' })).toHaveCount(0);
    expect((await database.pool.query('select value from tag_votes where article_id = $1 and tag_id = $2', [articleId, tag])).rows).toEqual([{ value: -1 }]);
    await neutral.click();
    await expect(page.getByRole('group', { name: 'Previously voted detached tags' })).toContainText('Local topic');
    await tagCheckbox.check();
    await submit.click();
    await expect(page.getByRole('group', { name: 'Previously voted detached tags' })).toContainText('Neutral');
    await page.getByRole('button', { name: 'Remove vote for tag: Local topic' }).click();
    await expect(page.getByRole('group', { name: 'Previously voted detached tags' })).toHaveCount(0);
    await expect(feedback.getByRole('status')).toHaveText('Vote removed.');
    await expect(neutral).toBeFocused();
    await page.getByRole('button', { name: 'Select for mail' }).click();
    await expect(page.getByRole('button', { name: 'Remove from mail queue' })).toBeVisible();
    await page.getByRole('button', { name: 'Remove from mail queue' }).click();
    await expect(page.getByRole('button', { name: 'Select for mail' })).toBeVisible();
    await page.getByRole('button', { name: 'Select for mail' }).click();
    await expect(page.getByRole('button', { name: 'Remove from mail queue' })).toBeVisible();
    const acknowledgement = await app.inject({ method: 'POST', url: '/api/v1/mail-queue/acknowledgements', headers: { host: `127.0.0.1:${port}` }, payload: { articleIds: [articleId] } });
    expect(acknowledgement.json().confirmed).toEqual([articleId]);
    await expect(page.getByText('Mail sent')).toBeVisible();
    await expect(page.getByRole('button', { name: /mail queue|Select for mail/ })).toHaveCount(0);
    await page.getByRole('button', { name: 'Mark read' }).click();
    await expect(page.getByRole('button', { name: 'Mark unread' })).toBeVisible();
    await expect(page.getByRole('button', { name: /Real server article/ })).toHaveCount(0);
    await page.getByLabel('Status').selectOption('read');
    await page.getByRole('button', { name: 'Apply filters' }).click();
    await expect(page.getByRole('button', { name: /Real server article/ })).toBeVisible();
  } finally {
    if (app) await app.close();
    if (database) await database.close();
    if (container) docker('rm', '--force', container);
  }
});
